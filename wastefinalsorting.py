def build_model(base_model_fn, name, input_shape, num_classes):
    base_model = base_model_fn(input_shape=input_shape, include_top=False, weights='imagenet')
    base_model.trainable = False

    inputs = Input(shape=input_shape)
    x = base_model(inputs, training=False)
    x = GlobalAveragePooling2D()(x)
    x = Dense(128, activation='relu')(x)
    outputs = Dense(num_classes, activation='softmax')(x)

    model = Model(inputs, outputs, name=name)
    model.compile(optimizer=Adam(learning_rate=0.001), loss='categorical_crossentropy', metrics=['accuracy'])
    return model

def plot_history(histories, labels):
    plt.figure(figsize=(14, 6))
    for history, label in zip(histories, labels):
        plt.plot(history.history['val_accuracy'], label=f'{label} (Val Acc)')
    plt.title("Validation Accuracy per Epoch")
    plt.xlabel("Epochs")
    plt.ylabel("Accuracy")
    plt.legend()
    plt.grid()
    plt.show()

def train_models(model_fns, model_names, image_size, train_gen, val_gen, epochs):
    histories = []
    accuracies = {}

    for fn, name in zip(model_fns, model_names):
        print(f"\nTraining {name}...")
        model = build_model(fn, name, image_size + (3,), train_gen.num_classes)
        history = model.fit(train_gen, validation_data=val_gen, epochs=epochs, verbose=1)
        histories.append(history)
        accuracies[name] = history.history['val_accuracy'][-1]

    return histories, accuracies

