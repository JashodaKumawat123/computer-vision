def get_class_names(generator):
    """Extract ordered class names from the generator."""
    class_indices = generator.class_indices
    return [cls for cls, idx in sorted(class_indices.items(), key=lambda x: x[1])]

def get_predictions(model, generator):
    """Fetch a batch of data and make predictions."""
    test_images, test_labels = next(generator)
    predictions = model.predict(test_images)
    predicted_labels = np.argmax(predictions, axis=1)
    true_labels = np.argmax(test_labels, axis=1)
    return test_images, true_labels, predicted_labels

